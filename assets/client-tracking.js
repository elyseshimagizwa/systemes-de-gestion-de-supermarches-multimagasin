(() => {
    const counter = document.getElementById('client-unread');
    const message = document.getElementById('client-update-message');
    const list = document.getElementById('client-notifications');
    const orders = document.getElementById('client-orders');
    let latest = null, busy = false, ordersHtml = null;
    function render(data) {
        counter.textContent = data.unread;
        const newest = Number(data.notifications[0]?.id || 0);
        if (latest !== null && newest > latest) message.textContent = 'Nouvelle notification : ' + data.notifications[0].message;
        else message.textContent = 'Suivi actualisé à ' + new Date().toLocaleTimeString('fr');
        latest = Math.max(latest || 0, newest);
        if (list) {
            list.replaceChildren();
            if (!data.notifications.length) list.textContent = 'Aucune notification pour le moment.';
            data.notifications.forEach(item => {
                const row = document.createElement('article');
                row.className = 'rounded-xl bg-white p-4';
                const title = document.createElement('strong');
                title.textContent = item.titre + (Number(item.lu) ? '' : ' — Non lue');
                const text = document.createElement('p'); text.textContent = item.message;
                const date = document.createElement('p'); date.textContent = item.created_at;
                row.append(title, text, date);
                if (item.commande_id) {
                    const link = document.createElement('a');
                    link.href = 'mes_commandes.php#commande-' + Number(item.commande_id);
                    link.textContent = 'Voir la commande';
                    row.append(link);
                }
                if (!Number(item.lu)) {
                    const form = document.createElement('form');
                    form.method = 'post'; form.action = 'mes_commandes.php#notifications';
                    for (const [name, value] of Object.entries({csrf_token: list.dataset.csrf, notification_id: item.id})) {
                        const input = document.createElement('input'); input.type = 'hidden'; input.name = name; input.value = value; form.append(input);
                    }
                    const button = document.createElement('button'); button.textContent = 'Marquer comme lue'; form.append(button);
                    row.append(form);
                }
                list.append(row);
            });
        }
        if (orders && typeof data.orders_html === 'string' && ordersHtml !== data.orders_html) {
            // HTML generated by the owner-scoped PHP renderer, with escaped values.
            orders.innerHTML = data.orders_html;
            ordersHtml = data.orders_html;
        }
    }
    async function refresh() {
        if (busy || document.hidden) return;
        busy = true;
        try {
            const response = await fetch('client_notifications.php' + (orders ? '?orders=1' : ''), {cache: 'no-store', credentials: 'same-origin'});
            if (!response.ok || response.redirected) throw new Error('Suivi indisponible');
            render(await response.json());
        } catch (error) {
            message.textContent = 'Actualisation indisponible. Réessayez ou reconnectez-vous.';
        } finally { busy = false; }
    }
    document.addEventListener('visibilitychange', refresh);
    document.getElementById('refresh-tracking')?.addEventListener('click', refresh);
    refresh();
    setInterval(refresh, 20000);
})();
